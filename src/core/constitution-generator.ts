/**
 * Get language-specific guidelines
 */
function getLanguageGuidelines(templateType: TemplateType): string {
  switch (templateType) {
    case 'python':
      return `### Python

- Use type hints on all function signatures
- Include docstrings for all classes and public methods
- Use \`snake_case\` for functions and variables
- Use \`PascalCase\` for class names
- Import from \`src.\` package prefix (e.g., \`from src.module import Class\`)
- Never nest triple-quoted strings (\`'''\` inside \`'''\`)`;
    case 'typescript':
      return `### TypeScript

- Enable strict mode in tsconfig.json
- Prefer interfaces over type aliases for object shapes
- Use \`camelCase\` for functions and variables
- Use \`PascalCase\` for classes and interfaces
- Export types alongside implementations
- Avoid \`any\` — use \`unknown\` if type is truly unknown`;
    case 'javascript':
      return `### JavaScript

- Use modern ES6+ features (const, let, arrow functions)
- Use JSDoc comments for type documentation
- Use \`camelCase\` for functions and variables
- Use \`PascalCase\` for classes
- Prefer async/await over raw Promises`;
    case 'react':
      return `### React/TypeScript

- Use functional components with hooks
- Define prop types with TypeScript interfaces
- Use \`useState\`, \`useEffect\`, \`useMemo\` appropriately
- Keep components focused (single responsibility)
- Extract reusable logic into custom hooks`;
    case 'vue':
      return `### Vue/TypeScript

- Use Composition API with \`<script setup>\`
- Define props and emits with TypeScript
- Use \`ref\`, \`reactive\`, \`computed\` appropriately
- Keep components focused
- Use composables for reusable logic`;
    default:
      return `### ${templateType}

- Follow language-specific best practices
- Write clear, self-documenting code
- Include comments for complex logic`;
  }
}

/**
 * Write constitution to file
 */
export async function writeConstitution(options: ConstitutionOptions): Promise<string> {
  const content = generateConstitution(options);
  const constitutionPath = getConstitutionPath(options.outputDir);

  // Ensure .groot directory exists
  const dir = dirname(constitutionPath);
  if (!existsSync(dir)) {
    await mkdir(dir, { recursive: true });
  }

  await writeFile(constitutionPath, content, 'utf-8');
  return constitutionPath;
}
